# ---------------- CELL 4: Manual MapReduce Simulation (Map -> Shuffle/Sort -> Reduce) ----------------
import re
from collections import defaultdict

LOG_PATTERN = re.compile(
    r'(?P<ip>\S+) \S+ \S+ \[(?P<time>[^\]]+)\] "(?P<method>\S+) (?P<url>\S+) \S+" (?P<status>\d+) (?P<size>\d+)'
)

def parse_line(line):
    m = LOG_PATTERN.match(line)
    if not m:
        return None
    return m.groupdict()

def read_log(path):
    with open(path) as f:
        return [line.strip() for line in f if line.strip()]

# ---- MAP PHASE ----
# Each mapper emits (key, value) pairs. We simulate 3 different analyses.
def map_ip_count(record):
    return (record["ip"], 1)

def map_status_count(record):
    return (record["status"], 1)

def map_hour_traffic(record):
    # extract hour from "01/Sep/2026:13:45:02 +0000"
    hour = record["time"].split(":")[1]
    return (hour, 1)

def map_url_count(record):
    return (record["url"], 1)

def run_map_reduce(records, map_fn):
    # MAP
    mapped = [map_fn(r) for r in records]

    # SHUFFLE & SORT: group values by key
    shuffled = defaultdict(list)
    for key, value in mapped:
        shuffled[key].append(value)

    # REDUCE: sum values per key
    reduced = {key: sum(values) for key, values in shuffled.items()}
    return reduced

# Parse log into structured records (this is the "input split" stage)
raw_lines = read_log("access.log")
records = [r for r in (parse_line(l) for l in raw_lines) if r is not None]
print(f"Parsed {len(records)} valid records out of {len(raw_lines)} lines")

# Run each MapReduce job
ip_counts = run_map_reduce(records, map_ip_count)
status_counts = run_map_reduce(records, map_status_count)
hour_traffic = run_map_reduce(records, map_hour_traffic)
url_counts = run_map_reduce(records, map_url_count)

print("\n--- Top 5 IPs by request count (MapReduce) ---")
