class MRLogAnalysis(MRJob):

    def mapper(self, _, line):
        m = LOG_PATTERN.match(line)
        if m:
            yield m.group("status"), 1

    def reducer(self, key, values):
        yield key, sum(values)

if __name__ == "__main__":
    MRLogAnalysis.run()
